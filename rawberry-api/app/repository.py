"""Storage contract: every data operation requires explicit user scope."""
from typing import Any, Protocol

class StorageError(Exception):
    pass

class ResourceNotFound(Exception):
    pass

class ConversationBusy(Exception):
    pass

class Repository(Protocol):
    # Return the persisted embedding status for each document in batch order.
    def save_documents(self, user_id: str, documents: list[tuple[dict[str, Any], bytes, list[dict[str, Any]]]]) -> list[str]: ...
    def list_documents(self, user_id: str) -> list[dict[str, Any]]: ...
    def get_document_content(self, user_id: str, document_id: str) -> bytes: ...
    def list_chunks(self, user_id: str) -> list[dict[str, Any]]: ...
    def search_chunks(self, user_id: str, query: str, limit: int = 3) -> list[dict[str, Any]]: ...
    def get_system_prompt(self, user_id: str) -> str: ...
    def set_system_prompt(self, user_id: str, prompt: str) -> None: ...
    def create_conversation(self, user_id: str, title: str, domain: str = "education") -> dict[str, Any]: ...
    def list_conversations(self, user_id: str) -> list[dict[str, Any]]: ...
    def list_messages(self, user_id: str, conversation_id: str) -> list[dict[str, Any]]: ...
    def start_turn(self, user_id: str, conversation_id: str, message: str) -> dict[str, Any]: ...
    def finish_turn(self, user_id: str, conversation_id: str, turn_id: str, reply: str | None) -> None: ...
    
    # Conversation sharing methods
    # choose who can have access to a conversation, returns the list of user_ids that now have access
    def set_conversation_shares(self, user_id: str, conversation_id: str, recipient_ids: list[str]) -> list[str]: ...
    # list the users that currently have access to a conversation, returns a list of those users
    def list_conversation_shares(self, user_id: str, conversation_id: str) -> list[str]: ...
    # list the conversations that have been shared with specified user, returns a list of convo metadata
    def list_shared_conversations(self, user_id: str) -> list[dict[str, Any]]: ...
    # open one shared conversation 
    def get_shared_conversation(self, user_id: str, conversation_id: str) -> dict[str, Any]: ...

