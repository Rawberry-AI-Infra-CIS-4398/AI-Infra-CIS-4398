BEGIN;

CREATE EXTENSION IF NOT EXISTS vector;

-- ============================================================
-- Lookup tables
-- ============================================================

CREATE TABLE IF NOT EXISTS status (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE
);

-- The API finds document status by name, not by a fixed ID.
INSERT INTO status (status)
VALUES ('uploaded')
ON CONFLICT DO NOTHING;

INSERT INTO role (name)
VALUES ('user'), ('assistant'), ('system')
ON CONFLICT DO NOTHING;

-- ============================================================
-- Documents
--
-- user_id is an opaque identifier, including UUID
-- strings. Documents use corpus:medical or corpus:education
-- ============================================================

CREATE TABLE IF NOT EXISTS document (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,

    user_id TEXT NOT NULL
        CHECK (user_id ~ '^[!-~]{1,128}$'),

    filename TEXT NOT NULL,
    file_type TEXT NOT NULL,
    size_bytes BIGINT NOT NULL
        CHECK (size_bytes >= 0),

    embedding_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (
            embedding_status IN ('pending', 'completed', 'failed')
        ),

    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
        CHECK (jsonb_typeof(metadata) = 'object'),

    status_id BIGINT NOT NULL
        REFERENCES status(id),

    -- metadata
    title TEXT,
    header TEXT,
    institution TEXT,
    citation TEXT,
    publish_date DATE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_document_user_uploaded
    ON document(user_id, uploaded_at, id);

CREATE INDEX IF NOT EXISTS idx_document_status
    ON document(status_id);

-- Original uploaded file bytes, separate from extracted text.
CREATE TABLE IF NOT EXISTS document_content (
    document_id BIGINT PRIMARY KEY
        REFERENCES document(id) ON DELETE CASCADE,

    content BYTEA NOT NULL
);

-- ============================================================
-- Authors and document authorship
-- ============================================================

CREATE TABLE IF NOT EXISTS author (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS document_author (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    document_id BIGINT NOT NULL
        REFERENCES document(id) ON DELETE CASCADE,

    author_id BIGINT NOT NULL
        REFERENCES author(id),

    CONSTRAINT uq_document_author
        UNIQUE (document_id, author_id)
);

CREATE INDEX IF NOT EXISTS idx_document_author_author
    ON document_author(author_id);

-- ============================================================
-- Extracted document chunks
-- ============================================================

CREATE TABLE IF NOT EXISTS chunk (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    doc_id BIGINT NOT NULL
        REFERENCES document(id) ON DELETE CASCADE,

    chunk_index BIGINT NOT NULL
        CHECK (chunk_index >= 0),

    content TEXT NOT NULL,

    page_number INTEGER
        CHECK (page_number IS NULL OR page_number >= 1),

    processing_status TEXT NOT NULL DEFAULT 'pending'
        CHECK (
            processing_status IN ('pending', 'completed', 'failed')
        ),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_chunk_index
        UNIQUE (doc_id, chunk_index)
);

-- ============================================================
-- Embeddings
-- ============================================================

CREATE TABLE IF NOT EXISTS embedding (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    chunk_id BIGINT NOT NULL
        REFERENCES chunk(id) ON DELETE CASCADE,

    vector VECTOR(768) NOT NULL,
    model TEXT NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_embedding_chunk_model
        UNIQUE (chunk_id, model)
);

-- ============================================================
-- User preferences
-- ============================================================

CREATE TABLE IF NOT EXISTS user_preference (
    user_id TEXT PRIMARY KEY
        CHECK (user_id ~ '^[!-~]{1,128}$'),

    system_prompt TEXT NOT NULL
        CHECK (length(system_prompt) <= 2000)
);

-- ============================================================
-- Conversations
-- ============================================================

CREATE TABLE IF NOT EXISTS chat_session (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,

    user_id TEXT NOT NULL
        CHECK (user_id ~ '^[!-~]{1,128}$'),

    title TEXT NOT NULL DEFAULT 'New conversation'
        CHECK (length(title) BETWEEN 1 AND 200),

    domain TEXT NOT NULL DEFAULT 'education'
        CHECK (domain IN ('medical', 'education')),

    description TEXT
        CHECK (
            description IS NULL
            OR length(description) <= 300
        ),

    doc_id BIGINT REFERENCES document(id),

    next_turn BIGINT NOT NULL DEFAULT 0
        CHECK (next_turn >= 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_ts TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_ts TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_chat_session_user_created
    ON chat_session(user_id, created_ts, id);

CREATE INDEX IF NOT EXISTS idx_chat_session_retention
    ON chat_session(updated_ts, id);

CREATE INDEX IF NOT EXISTS idx_chat_session_document
    ON chat_session(doc_id);

-- ============================================================
-- Active conversation history
--
-- Each row stores a user prompt and its generation outcome.
-- The API projects these rows into user/assistant messages.
-- ============================================================

CREATE TABLE IF NOT EXISTS chat_turn (
    id UUID PRIMARY KEY,

    session_id BIGINT NOT NULL
        REFERENCES chat_session(id) ON DELETE CASCADE,

    ordinal BIGINT NOT NULL
        CHECK (ordinal >= 1),

    prompt TEXT NOT NULL,
    reply TEXT,

    status TEXT NOT NULL
        CHECK (status IN ('pending', 'completed', 'failed')),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,

    CONSTRAINT uq_chat_turn_ordinal
        UNIQUE (session_id, ordinal),

    CONSTRAINT ck_chat_turn_reply
        CHECK (
            (status = 'completed' AND reply IS NOT NULL)
            OR
            (status IN ('pending', 'failed') AND reply IS NULL)
        ),

    CONSTRAINT ck_chat_turn_completion
        CHECK (
            (status = 'pending' AND completed_at IS NULL)
            OR
            (
                status IN ('completed', 'failed')
                AND completed_at IS NOT NULL
            )
        )
);

-- At most one generation may be pending per conversation.
CREATE UNIQUE INDEX IF NOT EXISTS uq_chat_turn_pending
    ON chat_turn(session_id)
    WHERE status = 'pending';

-- ============================================================
-- Message, Citation, and Access Structures
-- ============================================================

CREATE TABLE IF NOT EXISTS message (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    session_id BIGINT NOT NULL
        REFERENCES chat_session(id) ON DELETE CASCADE,

    role_id BIGINT NOT NULL
        REFERENCES role(id),

    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_message_session_time
    ON message(session_id, created_at, id);

CREATE INDEX IF NOT EXISTS idx_message_role
    ON message(role_id);

CREATE TABLE IF NOT EXISTS citation (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    message_id BIGINT NOT NULL
        REFERENCES message(id) ON DELETE CASCADE,

    chunk_id BIGINT NOT NULL
        REFERENCES chunk(id),

    retrieval_score DECIMAL NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_citation_message
    ON citation(message_id);

CREATE INDEX IF NOT EXISTS idx_citation_chunk
    ON citation(chunk_id);

CREATE TABLE IF NOT EXISTS chat_session_access (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    user_id TEXT NOT NULL
        CHECK (user_id ~ '^[!-~]{1,128}$'),

    session_id BIGINT NOT NULL
        REFERENCES chat_session(id) ON DELETE CASCADE,

    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uq_chat_session_access
        UNIQUE (user_id, session_id)
);

CREATE INDEX IF NOT EXISTS idx_chat_session_access_session
    ON chat_session_access(session_id);

-- ============================================================
-- Document modification timestamps
-- ============================================================

CREATE OR REPLACE FUNCTION set_document_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER trg_document_updated_at
BEFORE UPDATE ON document
FOR EACH ROW
EXECUTE FUNCTION set_document_updated_at();

-- ============================================================
-- Migration History
-- ============================================================

CREATE TABLE IF NOT EXISTS schema_migration (
    version TEXT PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

INSERT INTO schema_migration (version)
VALUES ('baseline_001')
ON CONFLICT DO NOTHING;

COMMIT;